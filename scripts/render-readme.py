#!/usr/bin/env python3
"""Writes the "More apps" grid into a README, between the registry:apps markers.

    render-readme.py --exclude <id> README.md [--registry apps.json|URL]

The app's own id is left out. Without markers the block goes in front of the "## License" heading. Run it
from an app's release step; nothing else touches the block. Stdlib only.
"""
import argparse
import html
import json
import re
import sys
import urllib.request

RAW = "https://raw.githubusercontent.com/danieltamas/registry/main"
BEGIN = "<!-- registry:apps:begin (generated by registry/scripts/render-readme.py, do not edit) -->"
END = "<!-- registry:apps:end -->"
COLUMNS = 3
KINDS = ("menu-bar", "terminal")


def load(source):
    if source.startswith("https://"):
        request = urllib.request.Request(source, headers={"User-Agent": "registry-render-readme"})
        with urllib.request.urlopen(request, timeout=10) as response:
            return json.load(response)
    with open(source, encoding="utf-8") as handle:
        return json.load(handle)


def cell(app):
    link = f"https://github.com/{app['repo']}"
    name = html.escape(app["name"])
    thumb = f"{RAW}/thumbs/{app['id']}.png"
    return (f'<td align="center" width="33%"><a href="{link}"><img src="{thumb}" width="64" alt="{name}"></a><br>'
            f'<b><a href="{link}">{name}</a></b><br><sub>{html.escape(app["pitch"])}</sub></td>')


def block(apps):
    rows = []
    for start in range(0, len(apps), COLUMNS):
        cells = [cell(app) for app in apps[start:start + COLUMNS]]
        cells += ['<td width="33%"></td>'] * (COLUMNS - len(cells))
        rows.append("<tr>\n" + "\n".join(cells) + "\n</tr>")
    return "\n".join([
        BEGIN,
        "## More apps",
        "",
        "Also by the same maker, all MIT, all free:",
        "",
        "<table>",
        *rows,
        "</table>",
        "",
        "Kept in sync with the [registry](https://github.com/danieltamas/registry); the menu bar apps list the same"
        " apps under Settings, More apps.",
        END,
    ])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("readme")
    parser.add_argument("--exclude", required=True)
    parser.add_argument("--registry", default=f"{RAW}/apps.json")
    args = parser.parse_args()

    registry = load(args.registry)
    others = [app for app in registry["apps"] if app["id"] != args.exclude]
    if len(others) == len(registry["apps"]):
        sys.exit(f"render-readme: no app with id {args.exclude!r} in the registry")
    others.sort(key=lambda app: KINDS.index(app["kind"]))

    with open(args.readme, encoding="utf-8") as handle:
        text = handle.read()
    generated = block(others)
    existing = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if existing.search(text):
        text = existing.sub(lambda _: generated, text)
    else:
        heading = re.search(r"^## License\s*$", text, re.M)
        if not heading:
            sys.exit("render-readme: no markers and no '## License' heading to insert before")
        text = text[:heading.start()] + generated + "\n\n" + text[heading.start():]
    with open(args.readme, "w", encoding="utf-8") as handle:
        handle.write(text)


if __name__ == "__main__":
    main()
